import AppKit

/// Hangs what is copied to the clipboard. Images, like a screenshot taken
/// with Control held or an image copied in Preview, are saved as a PNG in
/// Tendedero's own folder, and text as a .txt there, so on the line they
/// behave like any screenshot. Files copied in Finder hang where they are.
///
/// Each kind is off until the user turns it on. The pasteboard has no change
/// notification, so its change count is checked twice a second; what was
/// copied is only read once its types say which kind it is.
@MainActor
final class ClipboardWatcher {
    private let onCopy: (URL) -> Void
    /// The card already holding a text, so the same text copied again moves
    /// that card to the newest end rather than hanging a second one.
    private let findText: (String) -> URL?
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    /// The last image or text saved. Some apps put the same thing on the
    /// clipboard again; it hangs once, unless it has been taken down since.
    private var last: (data: Data, url: URL)?

    /// Images. The key predates text and files.
    static var isEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: "clipboardEnabled") }
        set { UserDefaults.standard.set(newValue, forKey: "clipboardEnabled") }
    }

    static var textEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: "clipboardTextEnabled") }
        set { UserDefaults.standard.set(newValue, forKey: "clipboardTextEnabled") }
    }

    static var filesEnabled: Bool {
        get { UserDefaults.standard.bool(forKey: "clipboardFilesEnabled") }
        set { UserDefaults.standard.set(newValue, forKey: "clipboardFilesEnabled") }
    }

    /// Whether any kind is on, and so whether the clipboard is watched at all.
    static var isWatching: Bool { isEnabled || textEnabled || filesEnabled }

    /// Marks what Tendedero puts on the clipboard itself, so a click on the
    /// line does not hang the same thing again.
    static let ownType = NSPasteboard.PasteboardType("app.tendedero.copy")

    /// Password managers and similar apps mark private or temporary copies,
    /// following nspasteboard.org. Those never hang, nor do Tendedero's own.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        ownType,
    ]

    /// Anything bigger is not a screenshot.
    private static let maxBytes = 64 * 1024 * 1024
    nonisolated private static let maxPixels = 80_000_000
    /// Text longer than this is a document, not a snippet.
    private static let maxTextBytes = 1024 * 1024
    /// Formatting can carry embedded pictures; past this it is left out and
    /// the text alone is kept.
    private static let maxRichBytes = 8 * 1024 * 1024
    /// Copying a whole folder's worth of files in Finder would sweep
    /// everything else off the line.
    private static let maxFiles = 10

    init(onCopy: @escaping (URL) -> Void, findText: @escaping (String) -> URL? = { _ in nil }) {
        self.onCopy = onCopy
        self.findText = findText
    }

    func start() {
        guard timer == nil else { return }
        // Whatever is on the clipboard already is old news.
        lastCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func check() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard let items = pb.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: $0.types) }) else { return }
        // A file copied in Finder also brings its name as text and its icon
        // as an image, so files are looked for first. Text from a spreadsheet
        // or a document comes with an image of itself, so text comes next.
        if items.contains(where: { $0.types.contains(.fileURL) }) {
            if Self.filesEnabled { hangFiles(items) }
        } else if items.contains(where: { $0.types.contains(.string) }) {
            if Self.textEnabled, let text = pb.string(forType: .string) { saveText(text, rich: richData(pb)) }
        } else if Self.isEnabled {
            readImage(pb, count: count)
        }
    }

    private func hangFiles(_ items: [NSPasteboardItem]) {
        let urls = items.compactMap { $0.string(forType: .fileURL).flatMap(URL.init(string:)) }
            .filter { $0.isFileURL && FileManager.default.fileExists(atPath: $0.path) }
        for url in urls.prefix(Self.maxFiles) { onCopy(url.standardizedFileURL) }
    }

    /// The formatting that came with copied text: RTF from apps like Word
    /// or Pages, or else HTML from a browser.
    private func richData(_ pb: NSPasteboard) -> (Data, String)? {
        for (type, ext) in [(NSPasteboard.PasteboardType.rtf, "rtf"), (.html, "html")] {
            if let data = pb.data(forType: type), !data.isEmpty, data.count <= Self.maxRichBytes { return (data, ext) }
        }
        return nil
    }

    private func saveText(_ text: String, rich: (Data, String)?) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              let data = text.data(using: .utf8), data.count <= Self.maxTextBytes else { return }
        if let existing = findText(text) {
            onCopy(existing)
            return
        }
        save(data, ext: "txt", rich: rich)
    }

    private func readImage(_ pb: NSPasteboard, count: Int) {
        guard let type = pb.availableType(from: [.png, .tiff]),
              let data = pb.data(forType: type), data.count <= Self.maxBytes,
              pb.changeCount == count else { return }
        // Decoding a large image takes a moment, so it happens off the main thread.
        DispatchQueue.global(qos: .userInitiated).async { [weak self] in
            let png = ClipboardWatcher.png(from: data, type: type)
            DispatchQueue.main.async {
                // Copied over again in the meantime: that copy is the one that counts.
                guard let png, NSPasteboard.general.changeCount == count else { return }
                self?.save(png, ext: "png")
            }
        }
    }

    /// PNG bytes are kept as they are; TIFF becomes PNG. Either way the image
    /// must decode and have a sane size.
    nonisolated private static func png(from data: Data, type: NSPasteboard.PasteboardType) -> Data? {
        guard let rep = NSBitmapImageRep(data: data),
              rep.pixelsWide > 0, rep.pixelsHigh > 0,
              rep.pixelsWide <= maxPixels / rep.pixelsHigh else { return nil }
        return type == .png ? data : rep.representation(using: .png, properties: [:])
    }

    private func save(_ data: Data, ext: String, rich: (Data, String)? = nil) {
        if let last, last.data == data, FileManager.default.fileExists(atPath: last.url.path) { return }
        let fm = FileManager.default
        var url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()).\(ext)")
        var n = 2
        while fm.fileExists(atPath: url.path) {
            url = Inbox.folder.appendingPathComponent("Clipboard \(Self.stamp()) \(n).\(ext)")
            n += 1
        }
        do {
            try fm.createDirectory(at: Inbox.folder, withIntermediateDirectories: true)
            try data.write(to: url, options: .atomic)
            // What people copy can be private: only they can read it.
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            // The formatting sits beside the text, under the same name, and
            // is written before the text hangs so its card knows of it.
            if let (richData, richExt) = rich {
                let richURL = url.deletingPathExtension().appendingPathExtension(richExt)
                try? richData.write(to: richURL, options: .atomic)
                try? fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: richURL.path)
            }
            last = (data, url)
            onCopy(url)
        } catch {
            try? fm.removeItem(at: url)
            log.error("Could not save a copy: \(error.localizedDescription, privacy: .public)")
        }
    }

    private static func stamp() -> String {
        let f = DateFormatter()
        f.locale = Locale(identifier: "en_US_POSIX")
        f.dateFormat = "yyyy-MM-dd 'at' HH.mm.ss"
        return f.string(from: Date())
    }
}
